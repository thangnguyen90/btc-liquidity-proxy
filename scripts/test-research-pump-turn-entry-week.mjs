import assert from 'node:assert/strict';
import {detect,simulate,stats} from './research-pump-turn-entry-week.mjs';
const S=300000;
const make=()=>Array.from({length:170},(_,i)=>({t:i*S,end:(i+1)*S-1,o:100,c:100,h:101,l:99,v:100,q:10000,buy:5000}));
const long=make();long[80]={...long[80],o:101,c:110,h:111,l:100,q:200000,buy:140000};
let found=detect(long,0,170*S);assert.equal(found.filter(e=>e.side==='LONG').length,1);
assert.equal(detect(long.slice(0,81),0,170*S)[0].at,found[0].at,'prefix detection identical');
const mutated=long.map((b,i)=>i>80?{...b,h:10000,c:9000,l:1}:b);
assert.deepEqual(detect(mutated,0,170*S).filter(e=>e.at<=long[80].end),detect(long,0,170*S).filter(e=>e.at<=long[80].end),'changing all future prices cannot change past signal/features');
assert.equal(detect(long.filter((_,i)=>i!==60),0,170*S).length,0,'history gap rejects signal');
const short=make();short[75]={...short[75],h:120,c:119,l:118,o:118};
for(let i=76;i<80;i++)short[i]={...short[i],o:119,c:119,h:120,l:118};
short[80]={...short[80],o:119,c:114,h:119,l:113,q:200000,buy:60000};
assert.equal(detect(short,0,170*S).filter(e=>e.side==='SHORT').length,1);
let r=make(),event={index:80,at:r[80].end,side:'LONG'};r[81]={...r[81],h:103,l:93};
let z=simulate(r,event,170*S);assert.equal(z.status,'SL');assert.equal(z.ambiguous,true);assert.ok(Math.abs(z.netRoe5x+30.7)<1e-8);
r[81]={...r[81],o:90,h:95,l:88};z=simulate(r,event,170*S);assert.equal(z.entry,90,'next open entry, not signal close');
r=make();r[82]={...r[82],o:90,h:93,l:88};z=simulate(r,event,170*S);assert.equal(z.exit,90,'stop gap uses worse open');
r=make();event={...event,side:'SHORT'};r[81]={...r[81],h:107,l:97};z=simulate(r,event,170*S);assert.equal(z.status,'SL');assert.equal(z.ambiguous,true);
r=make();r[81]={...r[81],h:101,l:97};z=simulate(r,event,170*S);assert.equal(z.status,'TP');assert.ok(Math.abs(z.netRoe5x-9.3)<1e-8);
z=simulate(r.slice(0,90),event,90*S);assert.equal(z.status,'TP');assert.equal(z.complete,false);assert.equal(stats([{symbol:'X',trade:z}]).n,0,'censored winners excluded too');
assert.equal(simulate(r.filter((_,i)=>i!==85),event,170*S).status,'DATA_GAP');
const minutes=Array.from({length:361},(_,i)=>({t:i*60000,end:(i+1)*60000-1,o:100,c:100,h:101,l:99}));
minutes[1].h=103;minutes[2].l=93;
const minuteTrade=simulate(minutes,{index:0,at:59999,side:'LONG'},361*60000,60000);
assert.equal(minuteTrade.status,'TP');assert.equal(minuteTrade.complete,true);assert.equal(minuteTrade.ambiguous,false,'1m can resolve a 5m both-hit candle');
console.log('PASS causal prefix, history gap, next open, long/short payoff, gap stop, ambiguity, censored cohort');
