const now = Date.parse('2026-09-26T14:00:00Z'); // 21h VN
const health = { updatedAt:now, btcTrendDir:'up' };
const candidate = {symbol:'TESTUSDT',side:'LONG',entryPrice:100.05,entryZone:{low:100,high:100.1},referenceLevel:100,confirmationAt:now-600000,retestAt:now-300000,lastClosed5m:100.05,lastClosed5mAt:now-1000,entryScore:80,executionEligible:true};
const payload = {generatedAt:now,candidates:[candidate],marketRegime:{evaluatedAt:now,dataReady:true,allowLongEntry:true}};
const ticks = new Map([['TESTUSDT',{markPrice:100.05,eventAt:now}]]);
const row = (p=payload,h=health,t=ticks,n=now,w='AUTO') => buildSessionRows(p,h,t,n,w)[0];
assert.equal(row().rank,3); assert.equal(row().contextClass,'context-long-ready'); assert.equal(row().executionEligible,false); assert.equal(row().binanceEligible,false);
assert.equal(row().observeOnly,true);
assert.equal(row(payload,{...health,btcTrendDir:'down'}).status,'NGƯỢC HƯỚNG BTC');
assert.equal(row(payload,{...health,btcTrendDir:'down'}).contextClass,'');
assert.equal(row(payload,{...health,updatedAt:now-121000}).status,'CHỜ BTC RÕ HƯỚNG');
assert.equal(row(payload,health,new Map()).status,'CHỜ GIÁ LIVE');
assert.equal(row(payload,health,new Map([['TESTUSDT',{markPrice:100,eventAt:now-11000}]])).live,false);
assert.equal(row({...payload,generatedAt:now-91000}).status,'DỮ LIỆU CŨ / THIẾU');
assert.equal(BTC_SESSION_CONTEXT_RULE_VERSION,'BTC_SESSION_CONTEXT_V2_IGNORE_LONG_MARKET_REGIME_20260926');
assert.equal(row({...payload,marketRegime:null}).rank,3,'missing market regime does not block the observe-only LONG row');
assert.equal(row({...payload,marketRegime:{...payload.marketRegime,allowLongEntry:false}}).rank,3,'allowLongEntry=false does not block the observe-only LONG row');
const jumped = row(payload,health,new Map([['TESTUSDT',{markPrice:105,eventAt:now}]]));
assert.equal(jumped.middle,100.05); assert.equal(jumped.status,'CHỜ GIÁ VỀ VÙNG · KHÔNG ĐUỔI');
assert.equal(row(payload,health,new Map([['TESTUSDT',{markPrice:99,eventAt:now}]])).status,'GIÁ ĐÃ PHÁ MỐC');
assert.equal(row(payload,health,ticks,now,'MORNING').status,'NGOÀI KHUNG ĐÃ CHỌN');
assert.equal(row({...payload,candidates:[{...candidate,retestAt:null}]}).status,'CHỜ RETEST 5m ĐÓNG');
assert.equal(row({...payload,candidates:[{...candidate,entryZone:null}]}).status,'DỮ LIỆU CŨ / THIẾU');
assert.equal(row({...payload,candidates:[candidate,{...candidate,side:'SHORT'}]}).dual,true);
assert.equal(row({...payload,candidates:[candidate,{...candidate,side:'SHORT'}]}).rank,0);
const shortPayload = { ...payload, candidates:[{...candidate,side:'SHORT',referenceLevel:100.1}], marketRegime:null };
assert.equal(row(shortPayload,{...health,btcTrendDir:'down'}).contextClass,'context-short-ready');
assert.equal(btcContext({...health,updatedAt:now+10000},now).direction,'UNKNOWN');
assert.equal(btcSessionVnDay(Date.parse('2026-09-26T16:59:59Z')),'2026-09-26');
assert.equal(btcSessionVnDay(Date.parse('2026-09-26T17:00:00Z')),'2026-09-27');
const history1 = updateBtcSessionWatchHistory(null,[candidate],now);
assert.equal(history1.version,BTC_SESSION_WATCH_HISTORY_VERSION);
assert.equal(history1.rows.length,1);
assert.equal(history1.rows[0].candidate.side,'LONG');
const history2 = updateBtcSessionWatchHistory(history1,[{...candidate,entryScore:88}],now+1000);
assert.equal(history2.rows.length,1);
assert.equal(history2.rows[0].firstSeenAt,now);
assert.equal(history2.rows[0].lastSeenAt,now+1000);
assert.equal(history2.rows[0].candidate.entryScore,88);
const retained = mergeBtcSessionWatchCandidates([],history2,now+2000)[0];
assert.equal(retained.retainedOnly,true);
assert.equal(retained.side,'LONG');
const retainedRow = buildSessionRows({...payload,candidates:[retained]},health,ticks,now+2000,'AUTO')[0];
assert.equal(retainedRow.rank,0);
assert.equal(retainedRow.status,'ĐÃ LƯU LONG · CHỜ NGUỒN TRỞ LẠI');
assert.equal(retainedRow.contextClass,'watch-retained');
assert.equal(retainedRow.executionEligible,false);
const oppositeHistory = updateBtcSessionWatchHistory(history2,[{...candidate,side:'SHORT',referenceLevel:100.1}],now+3000);
const longPlusSavedShort = mergeBtcSessionWatchCandidates([candidate],oppositeHistory,now+4000);
const longPlusSavedShortRows = buildSessionRows({...payload,candidates:longPlusSavedShort},health,ticks,now+4000,'AUTO');
assert.equal(longPlusSavedShortRows.find(item => item.side === 'LONG').dual,false);
assert.equal(longPlusSavedShortRows.find(item => item.side === 'SHORT').dual,false);
assert.equal(normalizeBtcSessionWatchHistory(history2,Date.parse('2026-09-27T17:00:00Z')).rows.length,0);
