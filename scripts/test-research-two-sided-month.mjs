import assert from 'node:assert/strict';
import { candidates, evaluate, dedupe } from './research-two-sided-month.mjs';
const H=3600000;
const rows=Array.from({length:180},(_,i)=>({t:i*H,end:(i+1)*H-1,o:100,h:101,l:99,c:100,v:10,q:1000}));
rows[100]={...rows[100],h:160,c:150,l:100};
const found=candidates(rows,72*H,180*H);
assert.equal(found.length,1);assert.equal(found[0].peakHour,100*H);assert.equal(found[0].base,100);
const mins=Array.from({length:60},(_,i)=>({t:100*H+i*60000,end:100*H+(i+1)*60000-1,o:150,h:151,l:149,c:150,v:1,q:150}));
mins[30]={...mins[30],h:160,l:70};
const c={...found[0],symbol:'TESTUSDT'};
const stable=rows.map((b,i)=>i>100?{...b,o:150,h:151,l:149,c:150}:b);
assert.equal(evaluate(c,stable,mins,180*H).status,'NO_MATCH','low within peak minute cannot prove post-peak dump');
const falling=stable.map((b,i)=>i===103?{...b,l:100}:b);
const e=evaluate(c,falling,mins,180*H);
assert.equal(e.status,'MATCH');assert.equal(e.drop24,37.5);assert.equal(e.baseTouched,true);assert.equal(e.complete72,true);
assert.equal(evaluate(c,stable.slice(0,104),mins,104*H).status,'PENDING_72H');
assert.equal(evaluate(c,falling.slice(0,104),mins,104*H).status,'MATCH','observed matched patterns can be immature');
assert.equal(evaluate(c,falling.filter(b=>b.t!==102*H),mins,180*H).status,'FUTURE_GAP');
assert.equal(evaluate(c,falling,mins.slice(1),180*H).status,'MINUTE_GAP');
assert.equal(candidates(rows.filter(b=>b.t!==70*H),72*H,180*H).length,0,'continuous prehistory required');
assert.equal(dedupe([e,{...e,peak:155,peakAt:e.peakAt+H}]).length,1);
assert.equal(dedupe([e,{...e,peak:155,peakAt:e.peakAt+73*H}]).length,2);
const laterLow=stable.map((b,i)=>i===130?{...b,l:100}:b);
assert.equal(evaluate(c,laterLow,mins,180*H).status,'MATCH','72h branch detects slower dump');
console.log('PASS research two-sided month: order ambiguity, gaps, censoring, thresholds, dedupe');
