import assert from 'node:assert/strict';
import {forwardOutcomes,summarize} from './research-prepump-confluence.mjs';
const M=60000,T=Date.UTC(2026,9,25),event={symbol:'TESTUSDT',observedAt:T+1000,delivery:{at:T+3000},price:100};
const bar=(t,o=100,h=102,l=99,c=101)=>[t,o,h,l,c,100,t+M-1,10000];
const rows=Array.from({length:360},(_,i)=>bar(T+(i+1)*M));
const a={heatmap:{target:{low:105},invalidationPrice:98}};
const r=forwardOutcomes([bar(T,100,200,1,110),...rows],{event,cutoff:T+361*M,assessment:a});
assert.equal(r.start,T+M);assert.equal(r.entry,100);assert.equal(r.horizons[6].complete,true);
assert.ok(Math.abs(r.horizons[1].mfePct-2)<1e-9);assert.ok(Math.abs(r.horizons[1].netReturnPct-.86)<1e-9);
assert.equal(r.targetOutcome,'NEITHER_6H');
const short=forwardOutcomes(rows,{event,cutoff:T+120*M,assessment:a});
assert.equal(short.horizons[1].complete,true);assert.equal(short.horizons[3].complete,false);assert.equal(short.horizons[3].returnPct,null);assert.equal(short.targetOutcome,'CENSORED');
const gap=[...rows];gap.splice(20,1);assert.equal(forwardOutcomes(gap,{event,cutoff:T+361*M}).status,'GAP_OR_INVALID');
const both=[...rows];both[0]=bar(T+M,100,106,97,101);
assert.equal(forwardOutcomes(both,{event,cutoff:T+361*M,assessment:a}).targetOutcome,'AMBIGUOUS_SAME_MINUTE');
const late=forwardOutcomes(rows,{event:{...event,delivery:{at:T+2*M+1000}},cutoff:T+361*M,assessment:a});
assert.equal(late.start,T+3*M);assert.equal(late.horizons[6].complete,false);
const totals=summarize([{event,assessment:{status:'FAIL'},forward:r},{event,assessment:{status:'UNAVAILABLE'},forward:short}]);
assert.equal(totals.ALL.count,2);assert.equal(totals.PASS.count,0);assert.equal(totals.PASS.horizons[1].avgNetPct,null);
assert.equal(totals.FAIL.count,1);assert.equal(totals.UNAVAILABLE.count,1);assert.equal(totals.ALL.horizons[6].complete,1);
console.log('PASS historical outcomes: no pre-alert wick, next-minute entry, per-horizon censoring, gaps, ambiguous touches, zero-pass statistics');
